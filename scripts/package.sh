#!/usr/bin/env bash
# Build a self-contained Harness Manager app image and native installer for the
# current OS/architecture. Run from any directory:
#
#   scripts/package.sh [all|app-image|installer] [X.Y.Z]
#
# The release workflow supplies X.Y.Z from its vX.Y.Z tag. Local builds default
# to 1.0.0. Signing is optional and is enabled by the environment variables
# documented in packaging/README.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MODE="${1:-all}"
VERSION="${2:-${APP_VERSION:-1.0.0}}"
APP_NAME="Harness Manager"
APP_ID="io.github.ghosthack.harnessmanager"
MAIN_CLASS="io.github.ghosthack.harnessmanager.HarnessManagerApp"
RUNTIME_MODULES="java.desktop,java.net.http,java.logging,java.management,java.sql,jdk.httpserver,jdk.unsupported,jdk.charsets"
# Windows Installer uses this identity to relate every Harness Manager release.
# It is already the UUID generated by jpackage for the historical vendor/name;
# pin it permanently so upgrades survive packaging-tool or branding changes.
WINDOWS_UPGRADE_UUID="228a3ccf-4cf0-5695-9bce-18aec018d679"
INPUT_DIR="$ROOT/target/jpackage-input"
PACKAGE_ROOT="$ROOT/target/jpackage"
IMAGE_DIR="$PACKAGE_ROOT/images"
RELEASE_DIR="$PACKAGE_ROOT/release"

if [[ "$MODE" != "all" && "$MODE" != "app-image" && "$MODE" != "installer" ]]; then
    echo "error: mode must be 'all', 'app-image', or 'installer'" >&2
    exit 2
fi
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "error: jpackage release version must be numeric X.Y.Z (got '$VERSION')" >&2
    exit 2
fi

case "$(uname -s)" in
    Darwin)
        PLATFORM="macos"
        ARCH="$(uname -m)"
        [[ "$ARCH" == "arm64" || "$ARCH" == "aarch64" ]] || {
            echo "error: this release currently supports macOS arm64 only" >&2
            exit 2
        }
        NATIVE_TYPE="dmg"
        IMAGE_PATH="$IMAGE_DIR/$APP_NAME.app"
        ASSET_PLATFORM="macos-arm64"
        ;;
    Linux)
        PLATFORM="linux"
        ARCH="$(uname -m)"
        [[ "$ARCH" == "x86_64" || "$ARCH" == "amd64" ]] || {
            echo "error: this release currently supports Linux x64 only" >&2
            exit 2
        }
        NATIVE_TYPE="deb"
        IMAGE_PATH="$IMAGE_DIR/$APP_NAME"
        ASSET_PLATFORM="linux-x64"
        ;;
    MINGW*|MSYS*|CYGWIN*)
        PLATFORM="windows"
        ARCH="$(uname -m)"
        [[ "$ARCH" == "x86_64" || "$ARCH" == "amd64" ]] || {
            echo "error: this release currently supports Windows x64 only" >&2
            exit 2
        }
        NATIVE_TYPE="exe"
        IMAGE_PATH="$IMAGE_DIR/$APP_NAME"
        ASSET_PLATFORM="windows-x64"
        ;;
    *)
        echo "error: unsupported packaging host: $(uname -s)" >&2
        exit 2
        ;;
esac

LICENSE_FILE="$ROOT/LICENSE"
NOTICES_FILE="$ROOT/THIRD-PARTY.md"
if [[ ! -f "$LICENSE_FILE" ]]; then
    LICENSE_FILE="$ROOT/oss/LICENSE"
    NOTICES_FILE="$ROOT/oss/THIRD-PARTY.md"
fi
[[ -f "$LICENSE_FILE" && -f "$NOTICES_FILE" ]] || {
    echo "error: LICENSE and THIRD-PARTY.md are required packaging inputs" >&2
    exit 1
}

shopt -s nullglob

sign_macos_jar_natives() {
    local signing_identity="$1"
    local signing_root archive archive_root entry native_count=0
    local -a native_entries

    signing_root="$(mktemp -d "${TMPDIR:-/tmp}/harness-manager-native-sign.XXXXXX")"

    for archive in "$INPUT_DIR"/*.jar; do
        native_entries=()
        while IFS= read -r entry; do
            case "$entry" in
                /*|../*|*/../*|*/..)
                    echo "error: unsafe native JAR entry: $entry" >&2
                    rm -rf "$signing_root"
                    return 1
                    ;;
                *.dylib|*.jnilib|*/pty4j-unix-spawn-helper)
                    native_entries+=("$entry")
                    ;;
            esac
        done < <(jar tf "$archive")
        (( ${#native_entries[@]} > 0 )) || continue

        archive_root="$signing_root/$(basename "$archive")"
        mkdir -p "$archive_root"
        (
            cd "$archive_root"
            jar xf "$archive" "${native_entries[@]}"
            for entry in "${native_entries[@]}"; do
                if [[ -n "${MACOS_KEYCHAIN:-}" ]]; then
                    codesign --force --sign "$signing_identity" \
                        --timestamp --options runtime \
                        --keychain "$MACOS_KEYCHAIN" "$entry"
                else
                    codesign --force --sign "$signing_identity" \
                        --timestamp --options runtime "$entry"
                fi
                codesign --verify --strict --verbose=2 "$entry"
            done
            zip -q "$archive" "${native_entries[@]}"
        )
        native_count=$((native_count + ${#native_entries[@]}))
    done

    rm -rf "$signing_root"
    if (( native_count == 0 )); then
        echo "error: no embedded macOS native libraries were found to sign" >&2
        return 1
    fi
    echo "==> Signed $native_count embedded macOS native libraries"
}

if [[ "$MODE" != "installer" ]]; then
    rm -rf "$INPUT_DIR" "$PACKAGE_ROOT"
    mkdir -p "$INPUT_DIR" "$IMAGE_DIR" "$RELEASE_DIR"

    echo "==> Staging the $ASSET_PLATFORM runtime dependencies"
    bash "$ROOT/scripts/build.sh" -Pdist -DskipTests -Drevision="$VERSION" clean package
    mkdir -p "$INPUT_DIR" "$IMAGE_DIR" "$RELEASE_DIR"
    cp "$ROOT/target/harness-manager-$VERSION.jar" "$INPUT_DIR/"
    python3 "$ROOT/scripts/stage-pty-natives.py" "$INPUT_DIR/harness-manager-$VERSION.jar" "$INPUT_DIR/pty4j-native" "$ASSET_PLATFORM"

    cp "$LICENSE_FILE" "$INPUT_DIR/LICENSE"
    cp "$NOTICES_FILE" "$INPUT_DIR/THIRD-PARTY.md"
    bash "$ROOT/scripts/stage-release-licenses.sh" "$INPUT_DIR"

    APP_JARS=("$INPUT_DIR/harness-manager-$VERSION.jar")
    if (( ${#APP_JARS[@]} != 1 )); then
        echo "error: expected one staged harness-manager-$VERSION.jar" >&2
        exit 1
    fi
    MAIN_JAR="$(basename "${APP_JARS[0]}")"

    # Apple's notary service recursively scans native binaries stored inside
    # dependency JARs. jpackage signs the app image, but it cannot reach into
    # those archives, so sign and timestamp the embedded Mach-O libraries
    # before the JARs are copied into the image.
    if [[ "$PLATFORM" == "macos" && -n "${MACOS_SIGNING_IDENTITY:-}" ]]; then
        echo "==> Signing embedded macOS native libraries"
        sign_macos_jar_natives "$MACOS_SIGNING_IDENTITY"
        for native in "$INPUT_DIR/pty4j-native/darwin"/*; do
            native_args=(--force --sign "$MACOS_SIGNING_IDENTITY" --timestamp --options runtime)
            if [[ -n "${MACOS_KEYCHAIN:-}" ]]; then native_args+=(--keychain "$MACOS_KEYCHAIN"); fi
            codesign "${native_args[@]}" "$native"
            codesign --verify --strict "$native"
        done
    fi

    case "$PLATFORM" in
        macos)   ICON="$ROOT/packaging/icons/harness-manager.icns" ;;
        windows) ICON="$ROOT/packaging/icons/harness-manager.ico" ;;
        linux)   ICON="$ROOT/packaging/icons/harness-manager.png" ;;
    esac

    echo "==> Creating the self-contained application image"
    IMAGE_ARGS=(
        --type app-image
        --dest "$IMAGE_DIR"
        --name "$APP_NAME"
        --app-version "$VERSION"
        --vendor "ghosthack contributors"
        --description "A desktop manager for persistent coding-agent sessions"
        --copyright "Copyright © 2026 ghosthack contributors"
        --input "$INPUT_DIR"
        --main-jar "$MAIN_JAR"
        --main-class "$MAIN_CLASS"
        --add-modules "$RUNTIME_MODULES"
        --java-options "--add-modules=$RUNTIME_MODULES"
        --java-options '-Dpty4j.preferred.native.folder=$APPDIR/pty4j-native'
        --java-options "--enable-native-access=ALL-UNNAMED"
        --java-options "--sun-misc-unsafe-memory-access=allow"
    )
    if [[ -f "$ICON" ]]; then
        IMAGE_ARGS+=(--icon "$ICON")
    fi
    if [[ "$PLATFORM" == "macos" ]]; then
        IMAGE_ARGS+=(
            --mac-package-identifier "$APP_ID"
            --mac-package-name "$APP_NAME"
            --mac-app-category developer-tools
        )
    fi
    for worker in jmux harness-stimulator; do
        if [[ "$worker" == jmux ]]; then worker_class=io.github.ghosthack.jmux.Main; else worker_class=io.github.ghosthack.harnessstimulator.Main; fi
        properties="$PACKAGE_ROOT/$worker-launcher.properties"
        printf 'main-jar=%s\nmain-class=%s\nwin-console=true\njava-options=--add-modules=%s --enable-native-access=ALL-UNNAMED -Dpty4j.preferred.native.folder=$APPDIR/pty4j-native\n' \
            "$MAIN_JAR" "$worker_class" "$RUNTIME_MODULES" > "$properties"
        IMAGE_ARGS+=(--add-launcher "$worker=$properties")
    done
    jpackage "${IMAGE_ARGS[@]}"

    if [[ "$PLATFORM" == "linux" ]]; then
        # A child jpackage launcher inherits the parent's JVM re-execution marker.
        # Clear it before starting workers so their arguments remain program arguments.
        for worker in jmux harness-stimulator; do
            cp "$IMAGE_PATH/bin/$worker" "$IMAGE_PATH/bin/.$worker-native"
            cp "$IMAGE_PATH/lib/app/$worker.cfg" "$IMAGE_PATH/lib/app/.$worker-native.cfg"
            cat > "$IMAGE_PATH/bin/$worker" <<EOF
#!/bin/sh
unset _JPACKAGE_LAUNCHER
exec "\$(dirname "\$0")/.$worker-native" "\$@"
EOF
            chmod +x "$IMAGE_PATH/bin/$worker"
        done
    fi

    if [[ "$PLATFORM" == "macos" && -n "${MACOS_SIGNING_IDENTITY:-}" ]]; then
        echo "==> Signing the macOS application image"
        SIGN_ARGS=(
            --type app-image
            --app-image "$IMAGE_PATH"
            --mac-sign
            --mac-app-image-sign-identity "$MACOS_SIGNING_IDENTITY"
        )
        if [[ -n "${MACOS_KEYCHAIN:-}" ]]; then
            SIGN_ARGS+=(--mac-signing-keychain "$MACOS_KEYCHAIN")
        fi
        jpackage "${SIGN_ARGS[@]}"
    fi

    if [[ "$PLATFORM" == "windows" && -n "${WINDOWS_PFX_FILE:-}" ]]; then
        echo "==> Signing the Windows application launcher"
        for launcher in "$APP_NAME" jmux harness-stimulator; do
            pwsh -NoProfile -File "$ROOT/scripts/sign-windows.ps1" -Path "$IMAGE_PATH/$launcher.exe"
        done
    fi

    if [[ "${SKIP_PACKAGE_SMOKE:-false}" != "true" ]]; then
        echo "==> Smoke-testing the packaged runtime, worker launchers and PTY backend"
        bash "$ROOT/scripts/smoke-package.sh" "$IMAGE_PATH"
    fi

    if [[ "$MODE" == "app-image" ]]; then
        echo "application image: $IMAGE_PATH"
        exit 0
    fi
else
    [[ -d "$IMAGE_PATH" ]] || {
        echo "error: application image does not exist: $IMAGE_PATH" >&2
        echo "Run app-image mode before installer mode." >&2
        exit 1
    }
    [[ -d "$INPUT_DIR/THIRD-PARTY-LICENSES" ]] || {
        echo "error: staged license inputs do not exist in $INPUT_DIR" >&2
        echo "Run app-image mode before installer mode." >&2
        exit 1
    }
    rm -rf "$RELEASE_DIR" "$PACKAGE_ROOT/license-artifact"
    mkdir -p "$RELEASE_DIR"
fi

echo "==> Creating the $NATIVE_TYPE installer"
INSTALLER_ARGS=(
    --type "$NATIVE_TYPE"
    --dest "$RELEASE_DIR"
    --name "$APP_NAME"
    --app-version "$VERSION"
    --vendor "ghosthack contributors"
    --description "A desktop manager for persistent coding-agent sessions"
    --copyright "Copyright © 2026 ghosthack contributors"
    --license-file "$LICENSE_FILE"
    --app-image "$IMAGE_PATH"
)
case "$PLATFORM" in
    macos)
        INSTALLER_ARGS+=(
            --mac-package-identifier "$APP_ID"
            --mac-package-name "$APP_NAME"
        )
        ;;
    windows)
        INSTALLER_ARGS+=(
            --win-upgrade-uuid "$WINDOWS_UPGRADE_UUID"
            --win-dir-chooser
            --win-menu
            --win-menu-group "$APP_NAME"
            --win-shortcut
        )
        ;;
    linux)
        INSTALLER_ARGS+=(
            --linux-package-name harness-manager
            --linux-deb-maintainer "ghosthack contributors"
            --linux-app-category Development
            --linux-menu-group Development
            --linux-shortcut
        )
        ;;
esac
jpackage "${INSTALLER_ARGS[@]}"

INSTALLERS=("$RELEASE_DIR"/*."$NATIVE_TYPE")
if (( ${#INSTALLERS[@]} != 1 )); then
    echo "error: expected exactly one .$NATIVE_TYPE installer in $RELEASE_DIR" >&2
    exit 1
fi
INSTALLER="$RELEASE_DIR/harness-manager-$VERSION-$ASSET_PLATFORM.$NATIVE_TYPE"
mv "${INSTALLERS[0]}" "$INSTALLER"

if [[ "$PLATFORM" == "windows" && -n "${WINDOWS_PFX_FILE:-}" ]]; then
    echo "==> Signing the Windows installer"
    pwsh -NoProfile -File "$ROOT/scripts/sign-windows.ps1" -Path "$INSTALLER"
fi

case "$PLATFORM" in
    windows)
        PORTABLE="$RELEASE_DIR/harness-manager-$VERSION-$ASSET_PLATFORM.zip"
        python3 "$ROOT/scripts/archive-app.py" "$IMAGE_DIR" "$APP_NAME" "$PORTABLE"
        ;;
    linux)
        PORTABLE="$RELEASE_DIR/harness-manager-$VERSION-$ASSET_PLATFORM.tar.gz"
        tar -C "$IMAGE_DIR" -czf "$PORTABLE" "$APP_NAME"
        ;;
esac

case "$PLATFORM" in
    macos)   RUNTIME_LEGAL="$IMAGE_PATH/Contents/runtime/Contents/Home/legal" ;;
    windows) RUNTIME_LEGAL="$IMAGE_PATH/runtime/legal" ;;
    linux)   RUNTIME_LEGAL="$IMAGE_PATH/lib/runtime/legal" ;;
esac
[[ -d "$RUNTIME_LEGAL" ]] || {
    echo "error: packaged Java runtime legal directory is missing: $RUNTIME_LEGAL" >&2
    exit 1
}

LICENSE_ARTIFACT_NAME="harness-manager-$VERSION-$ASSET_PLATFORM-licenses"
LICENSE_ARTIFACT_ROOT="$PACKAGE_ROOT/license-artifact"
LICENSE_ARTIFACT_DIR="$LICENSE_ARTIFACT_ROOT/$LICENSE_ARTIFACT_NAME"
rm -rf "$LICENSE_ARTIFACT_ROOT"
mkdir -p "$LICENSE_ARTIFACT_DIR"
cp -R "$INPUT_DIR/THIRD-PARTY-LICENSES/." "$LICENSE_ARTIFACT_DIR/"
mkdir -p "$LICENSE_ARTIFACT_DIR/runtime"
cp -RL "$RUNTIME_LEGAL/." "$LICENSE_ARTIFACT_DIR/runtime/"
(
    cd "$LICENSE_ARTIFACT_DIR"
    find . -type f -print | sed 's|^\./||' | LC_ALL=C sort > CONTENTS.txt
)
jar --create --no-manifest \
    --file "$RELEASE_DIR/$LICENSE_ARTIFACT_NAME.zip" \
    -C "$LICENSE_ARTIFACT_ROOT" "$LICENSE_ARTIFACT_NAME"

echo "release artifacts:"
find "$RELEASE_DIR" -maxdepth 1 -type f -print
